#!/usr/bin/env bash
# Measure pooled copies' ignored footprint and run the pool budget audit.
# Usage: fm-pool-footprint.sh measure <copy>
#        fm-pool-footprint.sh report <copy> [--top N]
#        fm-pool-footprint.sh --pool-audit < "<project>\t<copy>" rows
# measure prints the copy's ignored footprint in bytes: every path that
# `git ls-files --others --ignored --exclude-standard --directory` reports,
# summed with `du` without following symlinks (bin/fm-pool-footprint-lib.sh
# owns the measurement shared with fm-teardown.sh and fm-spawn.sh).
# report prints "<bytes>\t<shell-escaped path>" lines, each
# ignored directory expanded one level, largest first, at most N (default 10).
# --pool-audit is the scheduled sweep's post-run step: it reads one
# "<project>\t<copy>" row per line from stdin (bin/fm-pool-build-sweep.mjs
# emits the inventory it just swept), sums the footprint per project, and
# compares each total with FM_POOL_TOTAL_BUDGET_GB (default 80 decimal GB).
# When any project pool is over budget it writes state/pool-footprint.over-budget,
# a display line followed by sorted canonical project identities and exact
# byte totals used as wake keys, ensures state/pool-footprint.check.sh exists and is registered
# through bin/fm-check-register.sh, and exits 0. The check prints that line
# only when its wake keys differ from state/.pool-footprint-surfaced, then
# records those keys there, so the watcher wakes firstmate exactly once per distinct total.
# When every pool fits, the audit removes the record and the surfaced marker
# so a later crossing wakes again; the registered check stays in place and
# prints nothing. An unmeasurable copy is itself surfaced through the same
# record, naming the copy, so a broken copy can never silence the budget wake.
# Both budgets are documented in docs/configuration.md.
set -euo pipefail
SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
FM_ROOT=${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}
FM_HOME=${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}
STATE=${FM_STATE_OVERRIDE:-$FM_HOME/state}
# shellcheck source=bin/fm-pool-footprint-lib.sh
. "$SCRIPT_DIR/fm-pool-footprint-lib.sh"
# shellcheck source=bin/fm-pr-lib.sh
. "$SCRIPT_DIR/fm-pr-lib.sh"
# shellcheck source=bin/fm-check-lib.sh
. "$SCRIPT_DIR/fm-check-lib.sh"

usage() { sed -n '2,/^set -/p' "$0" | sed '$d;s/^# \{0,1\}//'; }

CHECK_ID=pool-footprint
RECORD="$STATE/pool-footprint.over-budget"
SURFACED="$STATE/.pool-footprint-surfaced"
CHECK="$STATE/$CHECK_ID.check.sh"

# The check's bytes never change between runs, so its registration hash is
# stable; the audit re-registers only when the file is missing or unbound.
check_body() {
  cat <<SH
#!/usr/bin/env bash
# Generated by bin/fm-pool-footprint.sh --pool-audit; surfaces one pool
# over-budget line per distinct total. Rebuilt and re-registered by the audit.
record='$RECORD'
surfaced='$SURFACED'
[ -f "\$record" ] && [ ! -L "\$record" ] || exit 0
keys=\$(sed '1d' -- "\$record") || exit 1
[ -n "\$keys" ] || exit 0
if [ -f "\$surfaced" ] && [ "\$keys" = "\$(cat -- "\$surfaced")" ]; then exit 0; fi
printf '%s\n' "\$keys" > "\$surfaced" || exit 1
head -n 1 -- "\$record"
SH
}

ensure_check_registered() {
  local tmp
  if [ -f "$CHECK" ] && [ ! -L "$CHECK" ] && check_body | cmp -s -- - "$CHECK" \
     && fm_custom_check_registered "$STATE" "$CHECK_ID"; then
    return 0
  fi
  umask 077
  tmp=$(mktemp "$STATE/.fm-pool-footprint-check.XXXXXX")
  check_body > "$tmp"
  chmod 0700 "$tmp"
  mv -f -- "$tmp" "$CHECK"
  "$SCRIPT_DIR/fm-check-register.sh" "$CHECK_ID" >/dev/null
}

pool_audit() {
  local budget project copy bytes line='' over=0 tmp unmeasurable=''
  local -a projects=() totals=() copies=() copy_bytes=() copy_projects=() keys=()
  budget=$(fm_pool_total_budget_bytes) || exit 2
  while IFS=$'\t' read -r project copy; do
    [ -n "$project" ] && [ -n "$copy" ] || continue
    project=$(cd "$project" && pwd -P) || return 1
    bytes=$(fm_pool_footprint_bytes "$copy") || {
      echo "error: cannot measure ignored footprint of $copy" >&2
      unmeasurable="$unmeasurable $copy"
      printf -v tmp '%q\tunmeasurable\t%q' "$project" "$copy"
      keys+=("$tmp")
      continue
    }
    copies+=("$copy"); copy_bytes+=("$bytes"); copy_projects+=("$project")
    local i found=0
    for ((i = 0; i < ${#projects[@]}; i++)); do
      if [ "${projects[$i]}" = "$project" ]; then
        totals[i]=$((totals[i] + bytes)); found=1; break
      fi
    done
    [ "$found" -eq 1 ] || { projects+=("$project"); totals+=("$bytes"); }
  done
  local i j top
  for ((i = 0; i < ${#projects[@]}; i++)); do
    [ "${totals[$i]}" -gt "$budget" ] || continue
    over=1
    printf -v tmp '%q\t%s' "${projects[$i]}" "${totals[$i]}"
    keys+=("$tmp")
    top=$(for ((j = 0; j < ${#copies[@]}; j++)); do
      [ "${copy_projects[$j]}" = "${projects[$i]}" ] || continue
      printf '%s\t%s\n' "${copy_bytes[$j]}" "${copies[$j]}"
    done | sort -rn -k1,1 | head -n 3 | while IFS=$'\t' read -r bytes copy; do
      printf ' %s (%s)' "$copy" "$(fm_pool_footprint_human "$bytes")"
    done)
    line="${line:+$line; }$(basename "${projects[$i]}") pool holds $(fm_pool_footprint_human "${totals[$i]}") of ignored output (budget FM_POOL_TOTAL_BUDGET_GB=$(fm_pool_footprint_gb "$budget") GB); largest copies:$top"
  done
  if [ -n "$unmeasurable" ]; then
    over=1
    line="${line:+$line; }pool footprint audit could not measure:$unmeasurable"
  fi
  mkdir -p "$STATE"
  if [ "$over" -eq 0 ]; then
    rm -f -- "$RECORD" "$SURFACED"
    [ ! -f "$CHECK" ] || ensure_check_registered
    return 0
  fi
  umask 077
  tmp=$(mktemp "$STATE/.fm-pool-footprint-record.XXXXXX")
  printf 'pool over budget: %s\n' "$line" > "$tmp"
  printf '%s\n' "${keys[@]}" | LC_ALL=C sort >> "$tmp"
  chmod 0600 "$tmp"
  mv -f -- "$tmp" "$RECORD"
  ensure_check_registered
  printf 'pool budget: %s\n' "$line"
}

case "${1:-}" in
  -h|--help) usage; exit 0 ;;
  measure)
    [ "$#" -eq 2 ] || { usage >&2; exit 2; }
    fm_pool_footprint_bytes "$2" || { echo "error: cannot measure ignored footprint of $2" >&2; exit 1; }
    ;;
  report)
    [ "$#" -ge 2 ] || { usage >&2; exit 2; }
    top=10
    if [ "$#" -eq 4 ] && [ "$3" = --top ]; then top=$4; elif [ "$#" -ne 2 ]; then usage >&2; exit 2; fi
    case "$top" in ''|*[!0-9]*|0) echo "error: --top requires a positive integer" >&2; exit 2 ;; esac
    fm_pool_footprint_report "$2" "$top" || { echo "error: cannot report ignored footprint of $2" >&2; exit 1; }
    ;;
  --pool-audit)
    [ "$#" -eq 1 ] || { usage >&2; exit 2; }
    pool_audit
    ;;
  *) usage >&2; exit 2 ;;
esac
